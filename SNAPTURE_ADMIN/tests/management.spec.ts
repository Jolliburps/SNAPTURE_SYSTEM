import { test, expect } from '@playwright/test'
import { readFileSync } from 'node:fs'
import path from 'node:path'

const credentials = JSON.parse(readFileSync(path.resolve('.local/e2e-credentials.json'), 'utf8'))

test('CESD management works across refreshes and respects staff permissions', async ({ browser, page }) => {
  const errors: string[] = []
  page.on('pageerror', (error) => errors.push(error.message))
  async function login(target: typeof page, access: 'owner' | 'staff') {
    await target.goto('/login')
    await target.getByLabel('Email address', { exact: false }).fill(credentials[access])
    await target.getByLabel('Password', { exact: false }).first().fill(credentials.password)
    await target.getByRole('button', { name: 'Sign in', exact: true }).click()
    await expect(target.getByRole('navigation', { name: 'Main navigation' })).toBeVisible()
  }
  await page.goto('/policies')
  await expect(page).toHaveURL(/\/login$/)
  await login(page, 'owner')
  await expect(page.getByRole('navigation', { name: 'Main navigation' }).getByRole('link')).toHaveCount(7)
  await expect(page.getByRole('link', { name: 'User Management' })).toHaveCount(0)
  await page.getByRole('link', { name: 'Policies & Guidelines', exact: true }).click()
  await page.getByRole('button', { name: 'Add Policy', exact: true }).click()
  const dialog = page.getByRole('dialog')
  await dialog.getByLabel('Title', { exact: true }).fill('Waste Segregation Guidelines')
  await dialog.getByLabel('Category', { exact: true }).fill('Guidelines')
  await dialog.getByLabel('Short Description').fill('Synthetic browser-test policy.')
  await dialog.getByLabel('Policy Content').fill('Separate recyclable, biodegradable, and residual waste.')
  await dialog.getByRole('button', { name: 'Save Policy' }).click()
  await expect(dialog).toHaveCount(0)
  await expect(page.getByText('Waste Segregation Guidelines', { exact: true })).toBeVisible()
  await page.reload()
  await expect(page.getByText('Waste Segregation Guidelines', { exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Edit Waste Segregation Guidelines' }).click()
  await dialog.getByRole('combobox', { name: 'Status', exact: true }).selectOption('Published')
  await dialog.getByRole('button', { name: 'Save Policy' }).click()
  await expect(page.locator('tbody .status-badge')).toHaveText('Published')
  await page.getByRole('button', { name: 'View Waste Segregation Guidelines' }).click()
  await expect(dialog.getByText('Separate recyclable, biodegradable, and residual waste.')).toBeVisible()
  await page.keyboard.press('Escape')
  await page.getByLabel('Search policies').fill('no match')
  await expect(page.getByText('No records found. Adjust your filters or add a record.')).toBeVisible()
  await page.getByLabel('Search policies').fill('')
  await expect(page.getByText('Waste Segregation Guidelines', { exact: true })).toBeVisible()
  await page.screenshot({ path: '.local/screenshots/policies-desktop.png', fullPage: true })

  await page.getByRole('link', { name: 'Educational Materials', exact: true }).click()
  await page.getByRole('button', { name: 'Add Material', exact: true }).click()
  await dialog.getByLabel('Title', { exact: true }).fill('Composting Basics')
  await dialog.getByLabel('Category', { exact: true }).fill('Composting')
  await dialog.getByRole('combobox', { name: 'Material Type', exact: true }).selectOption('PDF Guide')
  await dialog.getByLabel('Description', { exact: true }).fill('Synthetic test guide.')
  await dialog.getByLabel('Upload Material').setInputFiles({ name: 'guide.pdf', mimeType: 'application/pdf', buffer: Buffer.from('%PDF-1.4\n%%EOF') })
  await dialog.getByRole('button', { name: 'Save Material' }).click()
  await expect(dialog).toHaveCount(0)
  await page.reload()
  await expect(page.getByText('Composting Basics', { exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Edit Composting Basics' }).click()
  await dialog.getByLabel('Replace Attachment').setInputFiles({ name: 'replacement.pdf', mimeType: 'application/pdf', buffer: Buffer.from('%PDF-1.4\n%replacement\n%%EOF') })
  await dialog.getByRole('button', { name: 'Save Material' }).click()
  await expect(dialog).toHaveCount(0)
  await page.getByRole('button', { name: 'View Composting Basics' }).click()
  await expect(dialog.locator('iframe')).toHaveAttribute('src', /\/api\/cesd\/files\/materials\//)
  await page.keyboard.press('Escape')
  await page.screenshot({ path: '.local/screenshots/materials-desktop.png', fullPage: true })

  await page.getByRole('link', { name: 'Collection Schedule', exact: true }).click()
  await page.getByRole('button', { name: 'Add Schedule', exact: true }).click()
  await dialog.getByRole('combobox', { name: 'Barangay', exact: true }).selectOption('Molino 1')
  await dialog.getByLabel('Collection Date').fill('2026-10-02')
  await expect(dialog.getByText('Fri, Oct 2, 2026')).toBeVisible()
  await dialog.getByRole('button', { name: 'Save Schedule' }).click()
  await expect(dialog).toHaveCount(0)
  await page.getByLabel('Filter by month').fill('2026-10')
  await expect(page.getByRole('cell', { name: 'Molino 1', exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Edit Recyclable schedule' }).click()
  await dialog.getByRole('combobox', { name: 'Status', exact: true }).selectOption('Completed')
  await dialog.getByRole('button', { name: 'Save Schedule' }).click()
  await expect(page.locator('tbody .status-badge')).toHaveText('Completed')
  await page.getByLabel('Filter by barangay').selectOption('Bayanan')
  await expect(page.getByText('No records found. Adjust your filters or add a record.')).toBeVisible()
  await page.getByLabel('Filter by barangay').selectOption('')
  await expect(page.locator('tbody tr')).toHaveCount(1)
  await page.screenshot({ path: '.local/screenshots/schedules-desktop.png', fullPage: true })

  await page.getByRole('link', { name: 'Reports', exact: true }).click()
  await page.getByLabel('From', { exact: true }).fill('2026-01-01')
  await page.getByLabel('To', { exact: true }).fill('2026-12-31')
  await page.getByRole('button', { name: 'Generate Report' }).click()
  await expect(page.locator('tbody tr')).toHaveCount(3)
  const download = page.waitForEvent('download')
  await page.getByRole('button', { name: 'Export CSV' }).click()
  const csv = await download
  await csv.saveAs('.local/e2e-export.csv')
  expect(readFileSync('.local/e2e-export.csv', 'utf8')).toContain('Waste Segregation Guidelines')
  await page.screenshot({ path: '.local/screenshots/reports-desktop.png', fullPage: true })

  await page.getByRole('link', { name: 'Settings', exact: true }).click()
  await page.getByLabel('Full Name', { exact: true }).fill('Andrea Reyes Updated')
  await page.getByRole('button', { name: 'Save Changes' }).click()
  await expect(page.getByText('Your profile has been updated.')).toBeVisible()
  await page.reload()
  await expect(page.getByLabel('Full Name', { exact: true })).toHaveValue('Andrea Reyes Updated')
  await page.screenshot({ path: '.local/screenshots/profile-desktop.png', fullPage: true })
  await page.getByRole('tab', { name: 'Staff Access' }).click()
  await expect(page.getByText('Maria Santos', { exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Add Staff Account' }).click()
  await dialog.getByLabel('Full Name', { exact: true }).fill('Juan Dela Cruz')
  await dialog.getByLabel('Email Address', { exact: true }).fill('juan@example.test')
  await dialog.getByRole('button', { name: 'Save Account' }).click()
  await expect(dialog).toHaveCount(0)
  await expect(page.getByText('Juan Dela Cruz', { exact: true }).first()).toBeVisible()
  await page.screenshot({ path: '.local/screenshots/staff-desktop.png', fullPage: true })

  const staffContext = await browser.newContext()
  const staffPage = await staffContext.newPage()
  await login(staffPage, 'staff')
  await staffPage.getByRole('link', { name: 'Settings', exact: true }).click()
  await expect(staffPage.getByRole('tab', { name: 'Staff Access' })).toHaveCount(0)
  expect((await staffPage.request.get('/api/cesd/staff/')).status()).toBe(403)
  await page.getByRole('button', { name: 'Deactivate Maria Santos' }).click()
  await dialog.getByRole('button', { name: 'Confirm' }).click()
  await expect(dialog).toHaveCount(0)
  await staffPage.reload()
  await expect(staffPage).toHaveURL(/\/login$/)
  await page.getByRole('button', { name: 'Activate Maria Santos' }).click()
  await dialog.getByRole('button', { name: 'Confirm' }).click()
  await expect(dialog).toHaveCount(0)
  await staffContext.close()

  // Dashboard reads the same saved records as the management pages.
  await page.goto('/dashboard')
  const saved = await (await page.request.get('/api/cesd/dashboard/')).json()
  await expect(page.getByLabel('Dashboard month')).toHaveValue(saved.month)
  const verifyCounts = async (data: typeof saved) => {
    for (const [label, key] of [['Policies Published', 'policies'], ['Materials Published', 'materials'], ['Collection Schedules', 'schedules'], ['Saved Drafts', 'drafts']]) {
      await expect(page.getByRole('region', { name: label, exact: true }).locator('strong')).toHaveText(String(data.counts[key]))
    }
  }
  await verifyCounts(saved)
  expect(saved.counts.policies).toBe(1)
  expect(saved.counts.materials).toBe(0)
  expect(saved.counts.drafts).toBe(1)
  await expect(page.getByText('Total Users', { exact: true })).toHaveCount(0)
  await expect(page.getByText('User Registration Trend')).toHaveCount(0)
  await page.setViewportSize({ width: 1820, height: 864 })
  await page.screenshot({ path: '.local/screenshots/dashboard-desktop.png', fullPage: true })
  await page.getByRole('link', { name: 'Continue Editing Composting Basics' }).click()
  await expect(dialog).toHaveAccessibleName('Edit Material')
  await expect(dialog.getByLabel('Title', { exact: true })).toHaveValue('Composting Basics')
  await page.reload()
  await expect(dialog).toHaveAccessibleName('Edit Material')
  await dialog.getByRole('button', { name: 'Cancel' }).click()
  await expect(page).not.toHaveURL(/edit=/)
  await page.goto('/dashboard')
  await page.locator('.draft-destinations summary').click()
  await page.getByRole('link', { name: 'Policy drafts', exact: true }).click()
  await expect(page.getByLabel('Filter by status')).toHaveValue('Draft')
  await page.goto('/dashboard')
  await page.locator('.draft-destinations summary').click()
  await page.getByRole('link', { name: 'Educational material drafts', exact: true }).click()
  await expect(page.getByLabel('Filter by status')).toHaveValue('Draft')
  await expect(page.getByRole('cell', { name: 'Composting Basics', exact: true })).toBeVisible()
  await page.goto('/dashboard?month=2026-10')
  const schedulesPanel = page.getByRole('region', { name: 'Collection Schedules', exact: true }).filter({ has: page.locator('h2') })
  await expect(schedulesPanel.getByText('Completed', { exact: true })).toBeVisible()
  await schedulesPanel.getByRole('link', { name: 'View All' }).click()
  await expect(page.getByLabel('Filter by month')).toHaveValue('2026-10')
  for (const [title, destination] of [['Recent Policies & Guidelines', 'policies'], ['Latest Educational Materials', 'materials']]) {
    await page.goto('/dashboard')
    await page.getByRole('region', { name: title, exact: true }).getByRole('link', { name: 'View All' }).click()
    await expect(page).toHaveURL(new RegExp(`/${destination}$`))
  }
  await page.goto('/dashboard')
  for (const [month, lastDay] of [['2024-02', 'Feb 29, 2024'], ['2025-02', 'Feb 28, 2025'], ['2026-04', 'Apr 30, 2026'], ['2026-12', 'Dec 31, 2026']]) {
    await page.getByLabel('Dashboard month').fill(month)
    await expect(page.locator('.dashboard-date-range')).toContainText(lastDay)
    const data = await (await page.request.get(`/api/cesd/dashboard/?month=${month}`)).json()
    await verifyCounts(data)
    await expect(page.getByText(`No saved drafts updated in`, { exact: false })).toBeVisible()
  }
  await page.reload()
  await expect(page.getByLabel('Dashboard month')).toHaveValue('2026-12')
  let release: () => void = () => {}
  const gate = new Promise<void>((resolve) => { release = resolve })
  await page.route('**/api/cesd/dashboard/**', async (route) => { await gate; await route.fulfill({ status: 500, contentType: 'application/json', body: JSON.stringify({ detail: 'Database unavailable' }) }) })
  await page.getByLabel('Dashboard month').fill('2026-11')
  await expect(page.locator('.dashboard')).toHaveAttribute('aria-busy', 'true')
  await expect(page.getByRole('region', { name: 'Policies Published' }).locator('strong')).toHaveText('…')
  release()
  await expect(page.getByRole('alert')).toContainText('Database unavailable')
  await expect(page.getByRole('region', { name: 'Policies Published' }).locator('strong')).toHaveText('—')
  await page.unroute('**/api/cesd/dashboard/**')
  await page.getByRole('button', { name: 'Retry' }).click()
  await expect(page.getByRole('alert')).toHaveCount(0)
  await page.getByLabel('Dashboard month').fill(saved.month)
  await verifyCounts(saved)
  await page.setViewportSize({ width: 390, height: 844 })
  await expect.poll(() => page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBeTruthy()
  await page.screenshot({ path: '.local/screenshots/dashboard-mobile.png', fullPage: true, animations: 'disabled' })

  await page.setViewportSize({ width: 390, height: 844 })
  await page.goto('/policies')
  await expect(page.getByRole('heading', { name: 'Policies & Guidelines', exact: true })).toBeVisible()
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBeTruthy()
  await page.getByRole('button', { name: 'Open navigation' }).click()
  await expect(page.getByRole('link', { name: 'Reports', exact: true })).toBeVisible()
  await page.getByRole('link', { name: 'Reports', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Reports', exact: true, level: 1 })).toBeVisible()
  await expect(page.locator('.sidebar')).not.toBeInViewport()
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBeTruthy()
  await page.screenshot({ path: '.local/screenshots/reports-mobile.png', fullPage: true, animations: 'disabled' })
  expect(errors).toEqual([])
})
